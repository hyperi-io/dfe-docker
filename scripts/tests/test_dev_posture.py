"""`make dev` overwrites a minted admin password with the shipped default.

That is right on a box becoming a dev box and destructive anywhere else, so the
properties worth pinning are the refusal on a non-dev DFE_ENV and the backup taken
before the rewrite -- a minted password is unrecoverable once overwritten. A box
ALREADY on a dev posture keeps a non-default password: the stack replaced the
default itself, and writing it back locks the next run out.

`--real` is the opposite promise: it mints rather than overwrites, so what is
pinned there is that it never replaces a value that is already real.

DFE_ENV lives in .env and the password in env/engine.env, so each case is written
as one text and split the way `make init` splits it.
"""

import stat
import sys
from pathlib import Path

import pytest

import dev_posture

_MINTED = "s3cr3t-minted-value"
_PASSWORD_LINE = "DFE_AUTH_LOCAL_ADMIN_PASSWORD="
_DEPLOYMENT = f"""\
## A deployment's .env.
DFE_ENV=production
DFE_AUTH_LOCAL_ADMIN_PASSWORD={_MINTED}
DFE_UI_PORT=3000
"""
_DEV_BOX = _DEPLOYMENT.replace("production", "dev")
# What a tyre-kick leaves behind, and so what `make dev AUTH=real` is asked to
# repair: a dev posture running on the shipped default.
_TYRE_KICKED = _DEV_BOX.replace(_MINTED, "changeme")
_NO_POSTURE = f"""\
DFE_AUTH_LOCAL_ADMIN_PASSWORD={_MINTED}
DFE_UI_PORT=3000
"""


def _backups(*, directory: Path) -> list[Path]:
    """Return every backup `make dev` left of .env and env/engine.env, .env's first."""
    return sorted(
        [*directory.glob(".env.bak-*"), *(directory / "env").glob("engine.env.bak-*")]
    )


def _deploy(*, dotenv: Path, text: str) -> None:
    """Write the split of text into .env and env/engine.env."""
    dotenv_text, engine_text = _split(text=text)
    dotenv.write_text(dotenv_text, encoding="utf-8", newline="\n")
    engine_env = dotenv.parent / "env" / "engine.env"
    engine_env.parent.mkdir(exist_ok=True)
    engine_env.write_text(engine_text, encoding="utf-8", newline="\n")


def _split(*, text: str) -> tuple[str, str]:
    """Return (.env text, env/engine.env text) for one case's text."""
    lines = text.splitlines()
    engine = "".join(f"{line}\n" for line in lines if line.startswith(_PASSWORD_LINE))
    rest = "".join(
        f"{line}\n" for line in lines if not (line.startswith(_PASSWORD_LINE))
    )
    return rest, engine


def _state(*, dotenv: Path) -> tuple[str, str]:
    """Return (.env text, env/engine.env text) as they stand."""
    engine_env = dotenv.parent / "env" / "engine.env"
    return dotenv.read_text(encoding="utf-8"), engine_env.read_text(encoding="utf-8")


def test_a_non_dev_posture_is_refused(
    capsys: pytest.CaptureFixture[str], dotenv: Path
) -> None:
    _deploy(dotenv=dotenv, text=_DEPLOYMENT)

    assert dev_posture.main(argv=[]) == 2
    assert _state(dotenv=dotenv) == _split(text=_DEPLOYMENT)
    assert _backups(directory=dotenv.parent) == []
    assert "not a dev posture" in capsys.readouterr().err


def test_a_missing_dotenv_is_a_different_exit_code(dotenv: Path) -> None:
    assert dev_posture.main(argv=[]) == 1


def test_a_missing_engine_env_is_the_same_exit_code(
    capsys: pytest.CaptureFixture[str], dotenv: Path
) -> None:
    dotenv.write_text("DFE_ENV=dev\n", encoding="utf-8", newline="\n")

    assert dev_posture.main(argv=[]) == 1
    assert "env/engine.env" in capsys.readouterr().err


def test_the_rewrite_sets_both_keys_and_leaves_the_rest(dotenv: Path) -> None:
    _deploy(dotenv=dotenv, text=_NO_POSTURE)

    assert dev_posture.main(argv=[]) == 0
    dotenv_text, engine_text = _state(dotenv=dotenv)
    assert "DFE_ENV=dev" in dotenv_text
    assert "DFE_UI_PORT=3000" in dotenv_text
    assert "DFE_AUTH_LOCAL_ADMIN_PASSWORD=changeme" in engine_text
    assert _MINTED not in dotenv_text + engine_text


def test_the_live_password_is_rewritten_rather_than_its_commented_placeholder(
    dotenv: Path, engine_env: Path
) -> None:
    # A template copied by hand keeps its placeholder, which `make init` appends the minted line below
    dotenv.write_text("DFE_UI_PORT=3000\n", encoding="utf-8", newline="\n")
    placeholder = f"# {_PASSWORD_LINE}"
    engine_env.write_text(
        f"{placeholder}\n\n## Generated by `make init`\n{_PASSWORD_LINE}{_MINTED}\n",
        encoding="utf-8",
        newline="\n",
    )

    assert dev_posture.main(argv=[]) == 0
    lines = engine_env.read_text(encoding="utf-8").splitlines()
    assert lines[0] == placeholder
    assert lines[-1] == f"{_PASSWORD_LINE}changeme"
    assert _MINTED not in "\n".join(lines)


def test_an_absent_posture_is_written_rather_than_refused(dotenv: Path) -> None:
    _deploy(dotenv=dotenv, text=_NO_POSTURE)

    assert dev_posture.main(argv=[]) == 0
    assert "DFE_ENV=dev" in _state(dotenv=dotenv)[0]


def test_each_replaced_file_is_backed_up_0600_and_named(
    capsys: pytest.CaptureFixture[str], dotenv: Path
) -> None:
    _deploy(dotenv=dotenv, text=_NO_POSTURE)

    assert dev_posture.main(argv=[]) == 0
    backups = _backups(directory=dotenv.parent)
    assert [path.name.partition(".bak-")[0] for path in backups] == [
        ".env",
        "engine.env",
    ]
    assert backups[0].read_text(encoding="utf-8") == _split(text=_NO_POSTURE)[0]
    assert backups[1].read_text(encoding="utf-8") == _split(text=_NO_POSTURE)[1]
    err = capsys.readouterr().err
    for backup in backups:
        assert stat.S_IMODE(backup.stat().st_mode) == 0o600
        assert backup.name in err


def test_a_second_run_changes_nothing_and_takes_no_backup(dotenv: Path) -> None:
    _deploy(dotenv=dotenv, text=_NO_POSTURE)
    assert dev_posture.main(argv=[]) == 0
    settled = _state(dotenv=dotenv)

    assert dev_posture.main(argv=[]) == 0
    assert _state(dotenv=dotenv) == settled
    assert len(_backups(directory=dotenv.parent)) == 2


def test_a_dev_box_keeps_the_password_its_stack_recorded(
    capsys: pytest.CaptureFixture[str], dotenv: Path
) -> None:
    """The engine no longer accepts the default once `make post` replaced it."""
    _deploy(dotenv=dotenv, text=_DEV_BOX)

    assert dev_posture.main(argv=[]) == 0
    assert _state(dotenv=dotenv) == _split(text=_DEV_BOX)
    assert _backups(directory=dotenv.parent) == []
    assert "kept as recorded" in capsys.readouterr().err


def test_a_dev_box_on_the_default_stays_on_it(dotenv: Path) -> None:
    _deploy(dotenv=dotenv, text=_TYRE_KICKED)

    assert dev_posture.main(argv=[]) == 0
    assert _state(dotenv=dotenv) == _split(text=_TYRE_KICKED)
    assert _backups(directory=dotenv.parent) == []


def test_another_dev_posture_is_renamed_and_keeps_its_password(dotenv: Path) -> None:
    local_box = _DEV_BOX.replace("DFE_ENV=dev", "DFE_ENV=local")
    _deploy(dotenv=dotenv, text=local_box)

    assert dev_posture.main(argv=[]) == 0
    assert _state(dotenv=dotenv) == _split(text=_DEV_BOX)
    assert len(_backups(directory=dotenv.parent)) == 1


def test_real_mints_a_password_and_writes_a_non_dev_posture(dotenv: Path) -> None:
    _deploy(dotenv=dotenv, text=_TYRE_KICKED)

    assert dev_posture.main(argv=["--real"]) == 0
    dotenv_text, engine_text = _state(dotenv=dotenv)
    assert "DFE_ENV=production" in dotenv_text
    assert "DFE_UI_PORT=3000" in dotenv_text
    assert "DFE_AUTH_LOCAL_ADMIN_PASSWORD=changeme" not in engine_text
    assert engine_text.startswith(_PASSWORD_LINE)


def test_real_leaves_a_deployment_alone_rather_than_refusing_it(dotenv: Path) -> None:
    # The tyre-kick refuses a deployment because it would destroy the minted
    # password; --real has nothing to destroy, so it is a no-op instead.
    _deploy(dotenv=dotenv, text=_DEPLOYMENT)

    assert dev_posture.main(argv=["--real"]) == 0
    assert _state(dotenv=dotenv) == _split(text=_DEPLOYMENT)
    assert _backups(directory=dotenv.parent) == []


def test_real_keeps_a_minted_password_and_only_lifts_the_posture(
    dotenv: Path,
) -> None:
    _deploy(dotenv=dotenv, text=_DEV_BOX)

    assert dev_posture.main(argv=["--real"]) == 0
    dotenv_text, engine_text = _state(dotenv=dotenv)
    assert f"DFE_AUTH_LOCAL_ADMIN_PASSWORD={_MINTED}" in engine_text
    assert "DFE_ENV=production" in dotenv_text


def test_real_mints_a_distinct_password_each_time(dotenv: Path) -> None:
    _deploy(dotenv=dotenv, text=_TYRE_KICKED)
    assert dev_posture.main(argv=["--real"]) == 0
    first = _state(dotenv=dotenv)[1]

    _deploy(dotenv=dotenv, text=_TYRE_KICKED)
    assert dev_posture.main(argv=["--real"]) == 0

    assert _state(dotenv=dotenv)[1] != first


def test_the_flag_is_read_from_the_command_line(
    dotenv: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    _deploy(dotenv=dotenv, text=_TYRE_KICKED)
    monkeypatch.setattr(sys, "argv", ["dev_posture.py", "--real"])

    assert dev_posture.main() == 0
    assert "DFE_ENV=production" in _state(dotenv=dotenv)[0]
